import { createDecipheriv, pbkdf2Sync } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
const [input, output] = process.argv.slice(2);
const password = process.env.SOURCE_ARCHIVE_PASSWORD;
if (!input || !output || !password) throw new Error('Missing build input');
const bytes = readFileSync(input);
const split = bytes.indexOf(10);
if (split < 1 || split > 4096) throw new Error('Invalid build input header');
const meta = JSON.parse(bytes.subarray(0, split).toString('utf8'));
if (meta.version !== 1) throw new Error('Unsupported build input version');
const salt = Buffer.from(meta.salt, 'base64');
const iv = Buffer.from(meta.iv, 'base64');
const tag = Buffer.from(meta.tag, 'base64');
if (salt.length !== 16 || iv.length !== 12 || tag.length !== 16) throw new Error('Invalid build input parameters');
const key = pbkdf2Sync(password, salt, 210000, 32, 'sha256');
const decipher = createDecipheriv('aes-256-gcm', key, iv);
decipher.setAuthTag(tag);
const plaintext = Buffer.concat([decipher.update(bytes.subarray(split + 1)), decipher.final()]);
writeFileSync(output, plaintext, { mode: 0o600 });
